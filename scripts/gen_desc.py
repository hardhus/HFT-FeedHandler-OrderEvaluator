#!/usr/bin/env python3
"""Generate the event descriptor outputs from firmware/formats/event_desc.toml.

    scripts/gen_desc.py          write into the repository
    scripts/gen_desc.py DIR      write the same tree under DIR (used by just gen-check)
    scripts/gen_desc.py --list   print the output paths, one per line (just gen-check diffs them)

Outputs: the SV package (pack functions, offsets), the C++ header (structs) and the Python model
(struct formats, encode/decode). Stdlib only.
"""

import keyword
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SCHEMA = REPO / "firmware" / "formats" / "event_desc.toml"
SV_OUT = "firmware/rtl/core/gen/event_desc_pkg.sv"
CPP_OUT = "software/include/gen/event_desc.h"
PY_OUT = "firmware/tb/model/desc_gen.py"
OUTPUTS = (SV_OUT, CPP_OUT, PY_OUT)
BANNER = "Generated by scripts/gen_desc.py from firmware/formats/event_desc.toml. Do not edit: run just gen."

INT_SIZE = {"u8": 1, "u16": 2, "u32": 4, "u48": 6, "u64": 8}
ALIGN = {"u8": 1, "u16": 2, "u32": 4, "u48": 2, "u64": 8, "alpha": 1, "bytes": 1}
CPP_INT = {"u8": "std::uint8_t", "u16": "std::uint16_t", "u32": "std::uint32_t", "u64": "std::uint64_t"}
PY_FMT = {"u8": "B", "u16": "H", "u32": "I", "u64": "Q"}
# Names the three outputs cannot all use (keyword.iskeyword covers Python).
RESERVED = {
    "begin", "bit", "byte", "case", "char", "class", "default", "do", "double", "else", "end", "enum", "event",
    "first_match", "float", "for", "function", "if", "inout", "input", "int", "local", "logic", "long", "matches",
    "module", "new", "output", "package", "real", "reg", "short", "signed", "string", "struct", "this", "time",
    "type", "union", "unsigned", "void", "wire",
}  # fmt: skip


def check_schema(schema: dict) -> None:
    """Raise ValueError on the first rule the schema breaks."""
    version, bits = schema.get("version"), schema.get("ctrl_version_bits")
    if type(bits) is not int or not 1 <= bits <= 7:
        raise ValueError(f"ctrl_version_bits must be in 1..7, got {bits!r}")
    if type(version) is not int or not 1 <= version < 1 << bits:
        raise ValueError(f"version must be an integer in 1..{(1 << bits) - 1}, got {version!r}")
    entry, line = schema.get("entry_bytes"), schema.get("line_bytes")
    if line not in (32, 64) or entry != 2 * line:
        raise ValueError(f"an entry is two lines of 32 or 64 bytes, got {entry!r} and {line!r}")
    if schema.get("ctrl_bytes") != [line - 1, entry - 1]:
        raise ValueError(f"ctrl_bytes must be the last byte of each line, got {schema.get('ctrl_bytes')!r}")
    if schema.get("ctrl_phase_bit") not in range(bits, 8):
        raise ValueError(f"ctrl_phase_bit must be above the version bits, got {schema.get('ctrl_phase_bit')!r}")
    if not all(type(b) is int and 0 <= b < 8 for b in schema.get("flags", {}).values()):
        raise ValueError("flags: a bit number must be in 0..7")
    if len(set(schema.get("flags", {}).values())) != len(schema.get("flags", {})):
        raise ValueError("flags: two flags share a bit")

    kinds = schema.get("kind", [])
    if not kinds:
        raise ValueError("no entry kinds")
    codes = [k["code"] for k in kinds]
    if len(set(codes)) != len(codes) or not all(type(c) is int and 1 <= c <= 255 for c in codes):
        raise ValueError(f"kind codes must be unique and in 1..255 (0 is empty memory), got {codes}")
    if len({k["name"] for k in kinds}) != len(kinds):
        raise ValueError("two kinds share a name")
    if sum(1 for f in schema["common"] if f.get("kind_code")) != 1:
        raise ValueError("exactly one common field holds the kind code")
    names = {k["name"] for k in kinds}
    for f in schema["common"]:
        if bad := set(f.get("only", ())) - names:
            raise ValueError(f"{f['name']}: only names no kind: {sorted(bad)}")
    for kind in kinds:
        _check_fields(kind["name"], [*schema["common"], *kind["fields"]], schema)


def _check_fields(kind: str, fields: list[dict], schema: dict) -> None:
    used: dict[int, str] = {b: "ctrl" for b in schema["ctrl_bytes"]}
    seen: set[str] = set()
    for f in fields:
        name, byte, size, typ = f["name"], f["byte"], f["size"], f["type"]
        where = f"{kind}.{name}"
        if not name.isidentifier() or not name.islower() or name in RESERVED or keyword.iskeyword(name):
            raise ValueError(f"{where}: not a usable field name")
        if name in seen:
            raise ValueError(f"{where}: name used twice")
        seen.add(name)
        if typ not in ALIGN:
            raise ValueError(f"{where}: unknown type {typ!r}")
        if typ in INT_SIZE and size != INT_SIZE[typ]:
            raise ValueError(f"{where}: {typ} is {INT_SIZE[typ]} bytes, not {size}")
        if size < 1 or byte < 0 or byte + size > schema["entry_bytes"]:
            raise ValueError(f"{where}: outside the entry")
        if byte % ALIGN[typ]:
            raise ValueError(f"{where}: byte {byte} is not aligned to {ALIGN[typ]}")
        for b in range(byte, byte + size):
            if b in used:
                raise ValueError(f"{where}: byte {b} overlaps {used[b]}")
            used[b] = name


def load(path: Path | None = None) -> dict:
    schema = tomllib.loads((path or SCHEMA).read_text(encoding="utf-8"))
    check_schema(schema)
    return schema


def kind_fields(schema: dict, kind: dict) -> list[dict]:
    """A kind's fields in byte order, without the ctrl bytes."""
    common = [f for f in schema["common"] if kind["name"] in f.get("only", [kind["name"]])]
    return sorted([*common, *kind["fields"]], key=lambda f: f["byte"])


def layout(schema: dict, kind: dict) -> list[dict]:
    """Every byte of a kind in order: its fields, the ctrl bytes and the padding between them. A
    common field the kind does not fill (`only`) is padding here."""
    placed = [*kind_fields(schema, kind)]
    placed += [{"name": f"ctrl{i}", "byte": b, "size": 1, "type": "u8"} for i, b in enumerate(schema["ctrl_bytes"])]
    out, pos = [], 0
    for f in sorted(placed, key=lambda f: f["byte"]):
        if f["byte"] > pos:
            out.append({"name": f"pad{pos}", "byte": pos, "size": f["byte"] - pos, "type": "pad"})
        out.append(f)
        pos = f["byte"] + f["size"]
    return out


def gen_sv(schema: dict) -> str:
    line, entry = schema["line_bytes"], schema["entry_bytes"]
    version_bits, phase_bit = schema["ctrl_version_bits"], schema["ctrl_phase_bit"]
    out = [f"// {BANNER}", "package event_desc_pkg;"]
    out += [
        f"  localparam int unsigned DESC_BYTES = {entry};",
        f"  localparam int unsigned DESC_LINE_BYTES = {line};",
        f"  localparam int unsigned DESC_W = 8 * DESC_BYTES;",
        f"  localparam logic [{version_bits - 1}:0] DESC_VERSION = {version_bits}'d{schema['version']};",
        f"  localparam int unsigned DESC_CTRL_PHASE_BIT = {phase_bit};",
    ]
    out += [f"  localparam int unsigned DESC_CTRL{i}_OFS = {b};" for i, b in enumerate(schema["ctrl_bytes"])]
    out += [f"  localparam int unsigned DESC_FLAG_{n.upper()}_BIT = {b};" for n, b in schema["flags"].items()]
    out += ["", "  typedef enum logic [7:0] {"]
    kinds = schema["kind"]
    out += [
        f"    DESC_KIND_{k['name']} = 8'd{k['code']}{',' if i < len(kinds) - 1 else ''}  // {k['desc']}"
        for i, k in enumerate(kinds)
    ]
    out += ["  } desc_kind_e;", ""]
    for f in schema["common"]:
        out += [f"  // {f['desc']}"]
        out += [f"  localparam int unsigned DESC_{f['name'].upper()}_OFS = {f['byte']};"]
        out += [f"  localparam int unsigned DESC_{f['name'].upper()}_SIZE = {f['size']};"]
    for k in kinds:
        for f in k["fields"]:
            prefix = f"DESC_{k['name']}_{f['name'].upper()}"
            out += [f"  // {k['name']}: {f['desc']}"]
            out += [f"  localparam int unsigned {prefix}_OFS = {f['byte']};"]
            out += [f"  localparam int unsigned {prefix}_SIZE = {f['size']};"]
    for k in kinds:
        fields = kind_fields(schema, k)
        args = [f for f in fields if not f.get("writer") and not f.get("kind_code")]
        out += ["", f"  // {k['desc']}. ring_idx and the ctrl bytes are 0: see desc_stamp."]
        out += [f"  function automatic logic [DESC_W-1:0] desc_pack_{k['name'].lower()}("]
        decl = [f"    input logic [{8 * f['size'] - 1}:0] {f['name']}" for f in args]
        out += [",\n".join(decl)]
        out += ["  );", "    logic [DESC_W-1:0] e;", "    e = '0;"]
        for f in fields:
            if f.get("writer"):
                continue
            prefix = f"DESC_{f['name'].upper()}"
            if f in k["fields"]:
                prefix = f"DESC_{k['name']}_{f['name'].upper()}"
            value = f"DESC_KIND_{k['name']}" if f.get("kind_code") else f["name"]
            out += [f"    e[8*{prefix}_OFS+:8*{prefix}_SIZE] = {value};"]
        out += ["    return e;", "  endfunction"]
    writer = [f for f in schema["common"] if f.get("writer")]
    if [f["name"] for f in writer] != ["ring_idx"]:
        raise ValueError("desc_stamp knows one writer field, ring_idx")
    out += [
        "",
        "  // The fields the ring writer fills: ring_idx and both ctrl bytes.",
        "  function automatic logic [DESC_W-1:0] desc_stamp(input logic [DESC_W-1:0] e_in,",
        "                                                   input logic [31:0] ring_idx, input logic phase);",
        "    logic [DESC_W-1:0] e;",
        "    logic [7:0] ctrl;",
        "    ctrl = 8'(DESC_VERSION);",
        "    ctrl[DESC_CTRL_PHASE_BIT] = phase;",
        "    e = e_in;",
        "    e[8*DESC_RING_IDX_OFS+:8*DESC_RING_IDX_SIZE] = ring_idx;",
        "    e[8*DESC_CTRL0_OFS+:8] = ctrl;",
        "    e[8*DESC_CTRL1_OFS+:8] = ctrl;",
        "    return e;",
        "  endfunction",
        "endpackage",
    ]
    return "\n".join(out) + "\n"


def _cpp_member(f: dict) -> str:
    if f["type"] == "pad":
        return f"std::uint8_t {f['name']}[{f['size']}];"
    if f["type"] == "u48":
        return f"std::uint8_t {f['name']}[6];"
    if f["type"] == "alpha":
        return f"char {f['name']}[{f['size']}];"
    if f["type"] == "bytes":
        return f"std::uint8_t {f['name']}[{f['size']}];"
    return f"{CPP_INT[f['type']]} {f['name']};"


def cpp_struct_name(kind_name: str) -> str:
    return "".join(p.capitalize() for p in kind_name.split("_")) + "Entry"


def gen_cpp(schema: dict) -> str:
    version_mask = (1 << schema["ctrl_version_bits"]) - 1
    out = [
        f"// {BANNER}",
        "#pragma once",
        "",
        "#include <bit>",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace hft::desc {",
        "",
        'static_assert(std::endian::native == std::endian::little, "ring entries are little-endian");',
        "",
        f"inline constexpr std::uint8_t kVersion = {schema['version']};",
        f"inline constexpr std::size_t kEntryBytes = {schema['entry_bytes']};",
        f"inline constexpr std::size_t kLineBytes = {schema['line_bytes']};",
        f"inline constexpr std::uint8_t kCtrlPhase = 1u << {schema['ctrl_phase_bit']};",
        f"inline constexpr std::uint8_t kCtrlVersionMask = 0x{version_mask:02X};",
    ]
    out += [f"inline constexpr std::uint8_t kFlag_{n} = 1u << {b};" for n, b in schema["flags"].items()]
    out += ["", "enum class Kind : std::uint8_t {"]
    out += [f"  {k['name']} = {k['code']},  // {k['desc']}" for k in schema["kind"]]
    out += ["};", ""]
    for k in schema["kind"]:
        name = cpp_struct_name(k["name"])
        out += [f"// {k['desc']}", f"struct alignas({schema['entry_bytes']}) {name} {{"]
        for f in layout(schema, k):
            comment = f"  // {f['desc']}" if f.get("desc") else ""
            out += [f"  {_cpp_member(f)}{comment}"]
        out += ["};", f"static_assert(sizeof({name}) == kEntryBytes);"]
        for f in layout(schema, k):
            out += [f"static_assert(offsetof({name}, {f['name']}) == {f['byte']});"]
        out += [""]
    out += [
        "// A u48 field (little-endian, no native type).",
        "inline std::uint64_t load_u48(const std::uint8_t (&b)[6]) {",
        "  std::uint64_t v = 0;",
        "  for (int i = 5; i >= 0; --i) v = v << 8 | b[i];",
        "  return v;",
        "}",
        "",
        "}  // namespace hft::desc",
    ]
    return "\n".join(out) + "\n"


def _py_format(fields: list[dict]) -> str:
    fmt = "<"
    for f in fields:
        if f["type"] == "pad":
            fmt += f"{f['size']}x"
        elif f["type"] in PY_FMT:
            fmt += PY_FMT[f["type"]]
        else:
            fmt += f"{f['size']}s"
    return fmt


def gen_py(schema: dict) -> str:
    version_mask = (1 << schema["ctrl_version_bits"]) - 1
    kind_ofs = next(f["byte"] for f in schema["common"] if f.get("kind_code"))
    kind_name = next(f["name"] for f in schema["common"] if f.get("kind_code"))
    out = [
        f'"""{BANNER}',
        "",
        "encode() fills what it is given and leaves the rest 0; decode() returns every field. Integer fields",
        'are int; alpha and bytes fields are bytes of their exact size."""',
        "",
        "import struct",
        "from enum import IntEnum",
        "",
        f"VERSION = {schema['version']}",
        f"ENTRY_BYTES = {schema['entry_bytes']}",
        f"LINE_BYTES = {schema['line_bytes']}",
        f"CTRL_BYTES = {tuple(schema['ctrl_bytes'])}",
        f"CTRL_PHASE = 1 << {schema['ctrl_phase_bit']}",
        f"CTRL_VERSION_MASK = 0x{version_mask:02X}",
    ]
    out += [f"FLAG_{n.upper()} = 1 << {b}" for n, b in schema["flags"].items()]
    out += ["", "", "class Kind(IntEnum):"]
    out += [f"    {k['name']} = {k['code']}  # {k['desc']}" for k in schema["kind"]]
    out += ["", "", "# Kind -> field name -> (byte, size, type). Ctrl bytes included, padding not."]
    out += ["FIELDS: dict[Kind, dict[str, tuple[int, int, str]]] = {"]
    for k in schema["kind"]:
        out += [f"    Kind.{k['name']}: {{"]
        for f in layout(schema, k):
            if f["type"] != "pad":
                out += [f"        \"{f['name']}\": ({f['byte']}, {f['size']}, \"{f['type']}\"),"]
        out += ["    },"]
    out += ["}", "_FORMAT = {"]
    for k in schema["kind"]:
        out += [f"    Kind.{k['name']}: struct.Struct(\"{_py_format(layout(schema, k))}\"),"]
    out += ["}"]
    out += [
        "",
        "",
        "def encode(kind: Kind, **values: int | bytes) -> bytes:",
        "    fields = FIELDS[kind]",
        "    if unknown := set(values) - set(fields):",
        '        raise KeyError(f"{kind.name}: no field {sorted(unknown)}")',
        f'    values["{kind_name}"] = int(kind)',
        "    packed = []",
        "    for name, (_, size, typ) in fields.items():",
        "        v = values.get(name)",
        '        if typ in ("alpha", "bytes"):',
        '            v = bytes(size) if v is None else bytes(v)',
        "            if len(v) != size:",
        '                raise ValueError(f"{kind.name}.{name}: {len(v)} bytes, field is {size}")',
        '        elif typ == "u48":',
        '            v = (v or 0).to_bytes(6, "little")  # OverflowError if it does not fit',
        "        else:",
        "            v = v or 0",
        "        packed.append(v)",
        "    return _FORMAT[kind].pack(*packed)",
        "",
        "",
        "def decode(entry: bytes) -> dict[str, int | bytes]:",
        "    if len(entry) != ENTRY_BYTES:",
        '        raise ValueError(f"an entry is {ENTRY_BYTES} bytes, got {len(entry)}")',
        f"    kind = Kind(entry[{kind_ofs}])",
        "    fields = FIELDS[kind]",
        "    out = dict(zip(fields, _FORMAT[kind].unpack(entry), strict=True))",
        "    for name, (_, _, typ) in fields.items():",
        '        if typ == "u48":',
        '            out[name] = int.from_bytes(out[name], "little")',
        "    return out",
    ]
    return "\n".join(out) + "\n"


def render(schema: dict) -> dict[str, str]:
    return {SV_OUT: gen_sv(schema), CPP_OUT: gen_cpp(schema), PY_OUT: gen_py(schema)}


def main(argv: list[str]) -> None:
    if argv == ["--list"]:
        for rel in OUTPUTS:
            print(rel)
        return
    if len(argv) > 1:
        sys.exit(__doc__)
    out = Path(argv[0]) if argv else REPO
    try:
        schema = load()
    except ValueError as e:
        sys.exit(f"{SCHEMA}: {e}")
    for rel, text in render(schema).items():
        (out / rel).parent.mkdir(parents=True, exist_ok=True)
        (out / rel).write_bytes(text.encode("utf-8"))


if __name__ == "__main__":
    main(sys.argv[1:])
