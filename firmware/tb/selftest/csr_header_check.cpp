static_assert(sizeof(hft_csr_t) == 0xA000, "the map ends after SYMBOL");

// Field layout and constants used by software.
static_assert(HFT_CSR__GLOBAL__ID__ID_reset == 0x48465431, "ID is \"HFT1\"");
static_assert(HFT_CSR__GLOBAL__VERSION__VERSION_reset == 0x00050002, "F5 map + F3 FEED + F4 ITCH, SYMBOL");
static_assert(HFT_CSR__NET__NET_CTRL__RX_EN_bp == 0 && HFT_CSR__NET__NET_CTRL__ACCEPT_BCAST_bp == 1, "NET_CTRL");
static_assert(HFT_CSR__NET__LOCAL_MAC_HI__MAC_bw == 16, "LOCAL_MAC_HI holds MAC[47:32]");
static_assert(HFT_CSR__NET__FILTER__PORT_EN__PORT_bp == 0 && HFT_CSR__NET__FILTER__PORT_EN__PORT_bw == 16, "port");
static_assert(HFT_CSR__NET__FILTER__PORT_EN__EN_bm == 0x10000, "filter enable is bit 16");
static_assert(HFT_CSR__NET__NET_COMMIT__COMMIT_bm == 0x1 && HFT_CSR__STATS__STATS_CTRL__SNAPSHOT_bm == 0x1, "pulses");
static_assert(HFT_CSR__NET__NET_STATUS__COMMIT_BUSY_bm == 0x1, "commit_busy");
static_assert(HFT_CSR__FEED__FEED_CTRL__ENABLE_bm == 0x1 && HFT_CSR__FEED__FEED_CTRL__SESSION_CHECK_bm == 0x2 &&
                  HFT_CSR__FEED__FEED_CTRL__RESYNC_LEARN_bm == 0x4 && HFT_CSR__FEED__FEED_CTRL__FILTER_MASK_bm == 0xFF00,
              "FEED_CTRL");
static_assert(HFT_CSR__FEED__SESSION_2__BYTES_bm == 0xFFFF0000, "SESSION_2 holds bytes 8..9 in [31:16]");
static_assert(HFT_CSR__FEED__FEED_COMMIT__COMMIT_bm == 0x1 && HFT_CSR__FEED__FEED_COMMIT__RESYNC_bm == 0x2, "FEED_COMMIT");
static_assert(HFT_CSR__FEED__FEED_STATUS__COMMIT_BUSY_bm == 0x1, "FEED_STATUS");
static_assert(HFT_CSR__FEED__FEED_STATE__SYNCED_bm == 0x1 && HFT_CSR__FEED__FEED_STATE__EOS_bm == 0x2, "FEED_STATE");
static_assert(HFT_CSR__ITCH__ITCH_CTRL__CLASS_EN_bm == 0x3F && HFT_CSR__ITCH__ITCH_CTRL__CLASS_FILTER_bm == 0x3F00,
              "ITCH_CTRL");
